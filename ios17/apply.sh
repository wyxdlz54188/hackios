#!/bin/bash
# Get Apple's xnu-10002.1.13 (the kernel of Darwin 23.0.0 / iOS 17.0.0) and put this port's work on
# top of it: ios17/hakios-xnu-10002.1.13.patch is the 16.5 work rebased onto that tag, so it is one
# git apply and nothing else -- the new files (drivers, minicrypto, the APFS and ramfs file systems,
# the platform expert) are in the patch, not in a files/ directory beside it.
#
# usage: ios17/apply.sh [DIR]        (default: <repo>/xnu-src/xnu-10002.1.13)
# env:   XNU_URL=...                 fetch from an existing clone that has the tag (file:///path/to/xnu)
#        HAKIOS=/path/to/hakios      the common tree, for the configuration's XNU glue and HFS Plus
#
# The result is a git tree on the branch "hakios17" with the work uncommitted, which is how the common
# repository's xnu/export.sh expects to find a tree it saves a patch from.
#
# Two things this cannot bring by itself, both from the common tree (and both needed before a build):
#   the configuration's XNU glue   config/MASTER.hakios and bsd/dev/hakios.drivers.h are generated by
#                                  tools/hakios-config.py from the .config, for every build, and are
#                                  kept out of any saved patch on purpose;
#   HFS Plus (the data volume)     Apple's release that xnu/hfs/hfs.sh fetches and patches.
# With HAKIOS=/path/to/hakios both are done here; without it, the script says what is missing.
set -e
HERE=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
URL_OVERRIDE=${XNU_URL:-}
. "$HERE/version.env"
[ -n "$URL_OVERRIDE" ] && XNU_URL=$URL_OVERRIDE
DIR=${1:-$HERE/../xnu-src/$XNU_TAG}
PATCH=$HERE/hakios-$XNU_TAG.patch
HAKIOS=${HAKIOS:-$(cd "$HERE/../../.." && pwd)}

[ -e "$DIR" ] && { echo "apply.sh: $DIR already exists; not touching it" >&2; exit 1; }
[ -s "$PATCH" ] || { echo "apply.sh: no $PATCH" >&2; exit 1; }
mkdir -p "$(dirname "$DIR")"
DIR=$(cd "$(dirname "$DIR")" && pwd)/$(basename "$DIR")
git init -q "$DIR"
trap 'echo "apply.sh: failed; removing the incomplete $DIR" >&2; rm -rf "$DIR"' ERR
cd "$DIR"
git remote add origin "$XNU_URL"
git fetch -q --depth 1 origin "refs/tags/$XNU_TAG:refs/tags/$XNU_TAG"
git checkout -q -b hakios17 "$XNU_TAG"
[ "$(git rev-parse HEAD)" = "$XNU_BASE" ] || { echo "apply.sh: $XNU_TAG is $(git rev-parse HEAD), expected $XNU_BASE" >&2; false; }
echo 'BUILD/' >> .git/info/exclude
git apply --whitespace=nowarn "$PATCH"
echo "apply.sh: $XNU_TAG ($DARWIN, iOS 17.0.0) + $(grep -c '^diff --git' "$PATCH") files from the port"

if [ -f "$HAKIOS/tools/hakios-config.py" ]; then
	python3 "$HAKIOS/tools/hakios-config.py" kernel --tree "$DIR"
	[ -f "$HAKIOS/xnu/hfs/hfs.sh" ] && "$HAKIOS/xnu/hfs/hfs.sh" put "$DIR" && echo "apply.sh: HFS Plus put in"
	echo "apply.sh: the configuration's XNU glue and HFS Plus are in"
else
	echo "apply.sh: no common tree at $HAKIOS: config/MASTER.hakios, bsd/dev/hakios.drivers.h and" >&2
	echo "           HFS Plus are NOT in this tree -- HAKIOS=/path/to/hakios with the .config made." >&2
fi
